"""
FLYING MONKEY SHOW-CARD — a drawn alphabet, not a typeface.

Design-taste rule for this desk: letter, don't set. Everything display here is
built from the same brush as the mascot, so the headline and the monster came
off one hand.

The alphabet is a skeleton plus a weight class per stroke. Verticals carry 38,
horizontals 26, diagonals 32, curves 34 — the thick/thin of a flat brush held
at a constant angle, which is what a show-card writer's lettering actually is.
Set type has no such logic; that difference is the whole point.

Every glyph is then jittered a fraction of a degree and a unit or two off the
baseline, deterministically by position in the string, because a hand does not
repeat itself and a font cannot help doing so. The jitter is small enough that
you read it as warmth rather than as wobble.

Cap height 140, baseline at y=140, cap top at y=0.
"""

