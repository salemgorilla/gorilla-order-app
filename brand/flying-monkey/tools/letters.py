def _jitter(i, seed):
    """Deterministic wobble. A hand does not repeat; a font cannot help it."""
    h = (i * 2654435761 + seed * 40503) & 0xFFFFFFFF
    a = ((h >> 4) & 255) / 255.0 - 0.5
    b = ((h >> 12) & 255) / 255.0 - 0.5
    c = ((h >> 20) & 255) / 255.0 - 0.5
    return a * 2.2, b * 5.0, c * 0.035        # degrees, y offset, weight scale


def text(stroke_fn, s, x=0, y=0, size=140, track=6, weight=1.0, seed=1,
         profile=None):
    """Lay out a lettered string. Returns (paths, advance_width)."""
    k = size / 140.0
    paths, pen = [], 0.0
    for i, ch in enumerate(s.upper()):
        if ch not in G:
            ch = " "
        adv, strokes = G[ch]
        rot, dy, dw = _jitter(i, seed)
        ra = math.radians(rot)
        cx, cy = adv / 2.0, 70.0
        for item in strokes:
            pts, wk, closed, cor = item
            tp = []
            for px, py in pts:
                vx, vy = px - cx, py - cy
                rx = vx * math.cos(ra) - vy * math.sin(ra)
                ry = vx * math.sin(ra) + vy * math.cos(ra)
                tp.append((x + (pen + cx + rx) * k,
                           y + (cy + ry + dy) * k))
            paths.append(stroke_fn(tp, w=W[wk] * k * weight * (1 + dw),
                                   profile=profile, closed=closed,
                                   corners=cor))
        pen += adv + track
    return paths, (pen - track) * k


def width(s, size=140, track=6):
    k = size / 140.0
    pen = 0.0
    for ch in s.upper():
        pen += G.get(ch, G[" "])[0] + track
    return (pen - track) * k
